"""Token Parser Module for C-Language Compiler Tokenizer.

Parses the formatted text output generated by the compiled FLEX lexer
into structured Token objects, classifying tokens into compiler categories,
tracking source line numbers, and separating valid tokens from lexical errors.
"""

from dataclasses import dataclass, field
from typing import List, Dict, Set


# All token types emitted by the C-Language FLEX lexer
KEYWORD_TYPES: Set[str] = {
    "KEYWORD",
}

LITERAL_TYPES: Set[str] = {
    "INTEGER",
    "FLOAT",
    "STRING_LITERAL",
    "CHAR_LITERAL",
}

OPERATOR_TYPES: Set[str] = {
    # Arithmetic
    "PLUS",
    "MINUS",
    "MULTIPLY",
    "DIVIDE",
    "MODULO",
    "POWER",
    # Increment / Decrement
    "INC_OP",
    "DEC_OP",
    # Assignment
    "ASSIGN",
    "ADD_ASSIGN",
    "SUB_ASSIGN",
    "MUL_ASSIGN",
    "DIV_ASSIGN",
    "MOD_ASSIGN",
    # Relational
    "LT_OP",
    "GT_OP",
    "LE_OP",
    "GE_OP",
    "EQ_OP",
    "NE_OP",
    # Logical
    "LOGICAL_AND",
    "LOGICAL_OR",
    "LOGICAL_NOT",
    # Bitwise
    "BIT_AND",
    "BIT_OR",
    "BIT_XOR",
    "BIT_NOT",
    "LEFT_SHIFT",
    "RIGHT_SHIFT",
    # Member & Pointer
    "ARROW",
    "DOT",
    # Conditional
    "QUESTION",
    "COLON",
}

PUNCTUATOR_TYPES: Set[str] = {
    "LPAREN",
    "RPAREN",
    "LBRACE",
    "RBRACE",
    "LBRACKET",
    "RBRACKET",
    "SEMICOLON",
    "COMMA",
}

PREPROCESSOR_TYPES: Set[str] = {
    "PREPROCESSOR",
    "HEADER_FILE",
}

COMMENT_TYPES: Set[str] = {
    "COMMENT",
}

VALID_TOKEN_TYPES: Set[str] = (
    KEYWORD_TYPES
    | {"IDENTIFIER"}
    | LITERAL_TYPES
    | OPERATOR_TYPES
    | PUNCTUATOR_TYPES
    | PREPROCESSOR_TYPES
    | COMMENT_TYPES
)

ERROR_MARKER = "ERROR"


def get_token_category(token_type: str) -> str:
    """Classify token type into a high-level compiler category."""
    if token_type in KEYWORD_TYPES:
        return "Keyword"
    if token_type == "IDENTIFIER":
        return "Identifier"
    if token_type in LITERAL_TYPES:
        return "Literal"
    if token_type in OPERATOR_TYPES:
        return "Operator"
    if token_type in PUNCTUATOR_TYPES:
        return "Punctuator"
    if token_type in PREPROCESSOR_TYPES:
        return "Preprocessor"
    if token_type in COMMENT_TYPES:
        return "Comment"
    if token_type == "ERROR":
        return "Error"
    return "Other"


@dataclass
class Token:
    """Represents a single lexical token produced by the FLEX lexer."""
    index: int
    line_number: int
    lexeme: str
    token_type: str
    category: str = "Other"
    is_error: bool = False
    error_message: str = ""


@dataclass
class SymbolTableEntry:
    """Consolidated symbol table record for unique tokens."""
    lexeme: str
    category: str
    token_type: str
    count: int = 1
    lines: List[int] = field(default_factory=list)


@dataclass
class TokenParseResult:
    """Collection of parsed tokens and symbol table records."""
    tokens: List[Token] = field(default_factory=list)
    valid_tokens: List[Token] = field(default_factory=list)
    errors: List[Token] = field(default_factory=list)

    @property
    def total_count(self) -> int:
        return len(self.tokens)

    @property
    def valid_count(self) -> int:
        return len(self.valid_tokens)

    @property
    def error_count(self) -> int:
        return len(self.errors)

    def get_symbol_table(self) -> List[SymbolTableEntry]:
        """Generate a complete sorted symbol table of unique lexemes."""
        table: Dict[str, SymbolTableEntry] = {}
        for token in self.tokens:
            key = f"{token.lexeme}::{token.token_type}"
            if key in table:
                entry = table[key]
                entry.count += 1
                if token.line_number not in entry.lines:
                    entry.lines.append(token.line_number)
            else:
                table[key] = SymbolTableEntry(
                    lexeme=token.lexeme,
                    category=token.category,
                    token_type=token.token_type,
                    count=1,
                    lines=[token.line_number],
                )
        return sorted(table.values(), key=lambda e: (e.category, e.lexeme))


def parse_lexer_output(raw_output: str) -> TokenParseResult:
    """Parse raw stdout from lexer.exe into structured Token instances.

    Standard FLEX rule format:
        <LINE_NUM>\t<TOKEN_TYPE>\t<LEXEME>
    Fallback format (legacy 2-column):
        <LEXEME> <TOKEN_TYPE>

    Args:
        raw_output: Raw string output from lexer.exe.

    Returns:
        TokenParseResult containing all tokens, valid tokens, and error tokens.
    """
    result = TokenParseResult()
    lines = raw_output.splitlines()
    token_index = 1
    current_token: Token | None = None

    for line in lines:
        stripped = line.strip()
        if not stripped:
            continue

        # Check for tab-delimited format: line_num \t token_type \t lexeme
        if "\t" in line:
            parts = line.split("\t", 2)
            if len(parts) >= 3 and parts[0].strip().isdigit():
                line_no = int(parts[0].strip())
                token_type = parts[1].strip()
                lexeme = parts[2].rstrip("\r\n")

                is_err = token_type == "ERROR"
                category = get_token_category(token_type)
                err_msg = f"Invalid character '{lexeme}' at line {line_no}" if is_err else ""

                token = Token(
                    index=token_index,
                    line_number=line_no,
                    lexeme=lexeme,
                    token_type=token_type,
                    category=category,
                    is_error=is_err,
                    error_message=err_msg,
                )
                result.tokens.append(token)
                if is_err:
                    result.errors.append(token)
                else:
                    result.valid_tokens.append(token)

                current_token = token
                token_index += 1
                continue

        # If line does not match token header and we have a multi-line comment/string:
        if current_token is not None and current_token.token_type in {"COMMENT", "STRING_LITERAL"}:
            current_token.lexeme += "\n" + line
            continue

        # Fallback parsing for legacy 2-column or error marker format
        if "ERROR:" in line or "ERROR" in line:
            parts = stripped.rsplit(None, 1)
            lexeme = stripped.replace("ERROR: invalid character", "").replace("ERROR", "").strip()
            token = Token(
                index=token_index,
                line_number=1,
                lexeme=lexeme if lexeme else "?",
                token_type="ERROR",
                category="Error",
                is_error=True,
                error_message=f"Invalid character: {lexeme}",
            )
            result.tokens.append(token)
            result.errors.append(token)
            current_token = token
            token_index += 1
            continue

        parts = stripped.rsplit(None, 1)
        if len(parts) == 2:
            lexeme, token_type = parts
            cat = get_token_category(token_type)
            token = Token(
                index=token_index,
                line_number=1,
                lexeme=lexeme,
                token_type=token_type,
                category=cat,
                is_error=False,
                error_message="",
            )
            result.tokens.append(token)
            result.valid_tokens.append(token)
            current_token = token
            token_index += 1
        elif len(parts) == 1:
            token = Token(
                index=token_index,
                line_number=1,
                lexeme=parts[0],
                token_type="UNKNOWN",
                category="Error",
                is_error=True,
                error_message=f"Unrecognized token: {parts[0]}",
            )
            result.tokens.append(token)
            result.errors.append(token)
            current_token = token
            token_index += 1

    return result
